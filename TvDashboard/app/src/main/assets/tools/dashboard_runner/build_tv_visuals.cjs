/* Build the pinned, self-contained classic script so file:// previews work too.
   No third-party build tooling, network access or runtime module loader needed. */
const fs = require('node:fs');
const path = require('node:path');
const dir = path.resolve(__dirname, '../../dashboards/_shared/tv-signage');
const vendor = fs.readFileSync(path.join(dir, 'vendor/three.module.js'), 'utf8');
const match = /export\s*\{([^}]+)\};?\s*$/.exec(vendor);
if (!match || /^import\s/m.test(vendor)) throw Error('Unexpected Three.js module format; review the bundle builder before upgrading.');
const names = match[1].split(',').map(value => {
  const parts = value.trim().split(/\s+as\s+/);
  if (parts.some(part => !/^[A-Za-z_$][\w$]*$/.test(part))) throw Error('Unsupported module export');
  return parts.length === 2 ? `${parts[1]}: ${parts[0]}` : parts[0];
});
const scenes = fs.readFileSync(path.join(dir, 'scenes.js'), 'utf8')
  .replace(/^import \* as THREE from '\.\/vendor\/three\.module\.js';\s*/, '')
  .replace('export function mount(', 'function mount(');
if (/^(?:import|export)\s/m.test(scenes)) throw Error('Unexpected scene module format');
const bundle = `/* Generated by tools/dashboard_runner/build_tv_visuals.cjs.\n * Three.js r170: MIT, Copyright 2010-2024 Three.js Authors.\n * Full license: vendor/LICENSE.three.txt. Do not hand-edit this bundle. */\n(function () {\n'use strict';\nconst THREE = (function () {\n${vendor.slice(0, match.index)}\nreturn { ${names.join(', ')} };\n})();\n${scenes}\nwindow.TVScenes = { mount };\n})();\n`;
fs.writeFileSync(path.join(dir, 'visuals.js'), bundle);
console.log('Built self-contained TV visuals: ' + Buffer.byteLength(bundle) + ' bytes');
